#function for normalizing the strings
def normalize_string(s):
      def white_space_fix(text):
          return ' '.join(text.split())
      def remove_punc(text):
          exclude = set(string.punctuation)
          return ''.join(ch for ch in text if ch not in exclude)
      def lower(text):
          return text.lower()
      return white_space_fix(remove_punc(lower(s.strip())))

#this will be used for normalizing the actual and predicted labels
def list_normalization(lst):
    normalized_lst = []
    for l in lst:
        normalized_lst.append(normalize_string(l)) #comment this when you do not want to normalize
        #normalized_lst.append(l) #comment this when you want to normalize
    normalized_lst = list(set(normalized_lst))
    return normalized_lst

#generic zero-shot argument extraction prompt-chain for all the datasets and models
def zero_shot_argument_extraction_prompt_chain(model):
    prompt_template = PromptTemplate(
        input_variables=['role', 'role_question', 'document'],
        template = '''
        ##Instruction##
        Concisely extract the arguments for following role from the document. Return 'null' if any arugment is not present for a role. 
        Separate multiple arguments of a role values by semicolon (;). Precisely give the answer, no extra description is needed.

        ##Role Question##
        {role}: {role_question}

        ##Document##
        {document}

        Return arguments in JSON. Separate multiple arguments of a role values by semicolon (;).
        '''
    )
    prompt_chain = prompt_template | model | StrOutputParser()
    return prompt_chain

def cot_argument_extraction_prompt_chain(model):
    prompt_template = PromptTemplate(
        input_variables=['role', 'role_question', 'document'],
        template='''
        ##Instruction##
        Concisely extract the argumentss for the following role from the document. If no arguments are found, return 'null'. Follow these steps:
        1. Understand the role and the role-specific question.
        2. Analyze the document to identify spans that answer the question.
        3. Extract relevant arguments, separating multiple arguments with semicolons (;). Return 'null' if any arugment is not present for a role. Do not overgenerate arguments; be thoughtful and precise.  
        4. Return the result in JSON format.

        ##Role Question##
        {role}: {role_question}

        ##Document##
        {document}

        ##Example##
        Responsibility: What are the responsibilities of an Event Planner?  
        Document: "The Event Planner is responsible for booking venues, coordinating schedules with vendors, and managing budgets to ensure successful events."  

        ##JSON##
        {{"Responsibility": "booking venues; coordinating schedules with vendors; managing budgets"}}

        Extract and return the arguments for the role in the JSON format. Do not provide extra description.
        '''
    )
    prompt_chain = prompt_template | model | StrOutputParser()
    return prompt_chain

#generic prediction function. Compatible with most LLM API calls
def get_model_predictions(data, dataset_name, event_schema, mode, model_name, model_access_string, prompt_type):
    print(mode, model_access_string, prompt_type)
    if mode == 'openai':
        openai_key = os.getenv('OPENAI_API_KEY')
        if not openai_key:
            raise ValueError('OPENAI_API_KEY is not set')
        model = ChatOpenAI(openai_api_key=openai_key, temperature=0.0,
                           model=model_access_string, model_kwargs={"response_format": {"type": "json_object"}})
    elif mode == 'hug_api' and prompt_type =='zero-shot':
        hf_token = os.getenv('HUGGINGFACEHUB_API_TOKEN')
        if not hf_token:
            raise ValueError('HUGGINGFACEHUB_API_TOKEN is not set')
        model = HuggingFaceEndpoint(repo_id= model_access_string, temperature=0.01,
                                    max_new_tokens=64,  huggingfacehub_api_token=hf_token)
    elif mode == 'hug_api' and prompt_type =='cot':
      hf_token = os.getenv('HUGGINGFACEHUB_API_TOKEN')
      if not hf_token:
          raise ValueError('HUGGINGFACEHUB_API_TOKEN is not set')
      model = HuggingFaceEndpoint(repo_id= model_access_string, temperature=0.01,
                                  max_new_tokens=128,  huggingfacehub_api_token=hf_token)

    elif mode == 'anthropic':
        pass

    raw_prediction_dictionary = []
    inference_cnt = 0

    for dt in tqdm(data): #getting the predictions for all data
        new_dt = copy.deepcopy(dt)
        #pprint(dt)
        event, rl, context = dt['event'], dt['role'], dt['context']
        gt_arguments = dt['raw-initial-ground-truth']
        normalized_gt_arguments = copy.deepcopy(list_normalization(gt_arguments))

        #we will not process those arguments that are null or empty
        if 'null' in normalized_gt_arguments or len(normalized_gt_arguments)==0:
              continue #skip the arguments with ground-truth having null value

        
        if (dataset_name =='DiscourseEE'): #DiscourseEE dataset is a bit different than others
            role_question = event_schema[event][dt['argument-type']][rl]
        elif(dataset_name == 'PHEE'):
            role_question = event_schema[dt['argument-type']][rl]
        else:
            role_question = event_schema[event][rl]

        #print(f"{rl}:", role_question)
        input_dict = {
            'role': rl,
            'role_question': role_question,
            'document': context
        }

        #defining prompt chain based on prompt-type
        if prompt_type == 'zero-shot':
            prompt_chain = zero_shot_argument_extraction_prompt_chain(model) ##creating the prompt chain
        if prompt_type == 'cot':
            prompt_chain = cot_argument_extraction_prompt_chain(model)

        while True: ## to get rid of model overload error
            try:
                output = prompt_chain.invoke(input_dict)
                inference_cnt += 1
                #pprint(output)
                break
            except Exception as e:
                print(e)
                time.sleep(3)

        ##creating dictionary for each role for each sample with relevant values
        new_dt['initial-ground-truth'] = normalized_gt_arguments
        #print("output: ", rl, "||", output)
        new_dt['raw-initial-predictions'] = output

        #pprint(new_dt)
        raw_prediction_dictionary.append(new_dt)

    return raw_prediction_dictionary, inference_cnt